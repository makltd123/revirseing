function winAnsi() {
  const m = asciiBase();
  for (const [code, cp] of Object.entries(WIN_ANSI_HIGH)) {
    m.set(Number(code), String.fromCodePoint(cp));
  }
  // 0xA0..0xFF match Latin-1 / Unicode directly.
  for (let c = 0xa0; c <= 0xff; c++) m.set(c, String.fromCodePoint(c));
  return m;
}

