// Character encodings a simple (single-byte) PDF font can declare, as
// code -> Unicode maps, plus the glyph-name -> Unicode lookup that /Encoding
// /Differences needs.
//
// Codes 32..126 are ASCII in every encoding below except where noted.

function asciiBase() {
  const m = new Map();
  for (let c = 32; c <= 126; c++) m.set(c, String.fromCharCode(c));
  return m;
}

